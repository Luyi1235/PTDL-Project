def replace(paragraph, old, new):
    nodes = paragraph._p.xpath(".//w:t")
    full = "".join(t.text or "" for t in nodes)
    if full.count(old) != 1:
        raise ValueError(f"Expected one occurrence of {old!r}; found {full.count(old)}")
    start = full.index(old)
    stop = start + len(old)
    cursor = 0
    placed = False
    for node in nodes:
        text = node.text or ""
        begin, end = cursor, cursor + len(text)
        cursor = end
        if end <= start or begin >= stop:
            continue
        x, y = max(0, start - begin), min(len(text), stop - begin)
        node.text = text[:x] + (new if not placed else "") + text[y:]
        placed = True
        if node.text.startswith(" ") or node.text.endswith(" "):
            node.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")

count = 0
for index, replacements in edits.items():
    for old, new in replacements:
        replace(doc.paragraphs[index], old, new)
        count += 1

remaining = [(i, p.text) for i, p in enumerate(doc.paragraphs) if "：" in p.text or ":" in p.text]
if remaining:
    raise ValueError(f"Remaining colon paragraphs: {remaining}")
doc.save(output)
print(f"Revised {count} passages in {len(edits)} paragraphs. Saved: {output}")
