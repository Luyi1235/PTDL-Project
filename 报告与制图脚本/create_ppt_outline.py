def p(doc, label, text):
    para = doc.add_paragraph()
    para.paragraph_format.space_after = Pt(8)
    para.paragraph_format.line_spacing = 1.2
    r = para.add_run(label + "  ")
    r.bold = True
    para.add_run(text)


