def replace_in_paragraph(paragraph, old, new):
    nodes = paragraph._p.xpath(".//w:t")
    combined = "".join(n.text or "" for n in nodes)
    if combined.count(old) != 1:
        raise ValueError(f"Expected one match, found {combined.count(old)}: {old}")
    start = combined.index(old)
    end = start + len(old)
    offset = 0
    placed = False
    for node in nodes:
        text = node.text or ""
        left, right = offset, offset + len(text)
        offset = right
        if right <= start or left >= end:
            continue
        local_start, local_end = max(0, start - left), min(len(text), end - left)
        replacement = new if not placed else ""
        placed = True
        node.text = text[:local_start] + replacement + text[local_end:]
        if node.text.startswith(" ") or node.text.endswith(" "):
            node.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")

